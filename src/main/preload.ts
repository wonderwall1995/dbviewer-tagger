import { contextBridge, ipcRenderer } from 'electron'

contextBridge.exposeInMainWorld('electronAPI', {
  openCsv: () => ipcRenderer.invoke('dialog:openCsv'),
  localSave: (data: unknown) => ipcRenderer.invoke('local:save', data),
  localLoad: () => ipcRenderer.invoke('local:load'),
  localSetActiveFile: (presetName: string, fileName: string | null) => ipcRenderer.invoke('local:setActiveFile', presetName, fileName),
  localSavePreset: (name: string, data: unknown) => ipcRenderer.invoke('local:savePreset', name, data),
  localListPresets: () => ipcRenderer.invoke('local:listPresets'),
  localLoadPreset: (name: string) => ipcRenderer.invoke('local:loadPreset', name),
  localDeletePreset: (name: string) => ipcRenderer.invoke('local:deletePreset', name),
  localImportFile: (sourcePath: string) => ipcRenderer.invoke('local:importFile', sourcePath),
  localReadFile: (filePath: string) => ipcRenderer.invoke('local:readFile', filePath),
  localGetDownloadsPath: (root: 's3' | 'db') => ipcRenderer.invoke('local:getDownloadsPath', root),
  localListCsvTree: (root: 's3' | 'db', subPath?: string) => ipcRenderer.invoke('local:listCsvTree', root, subPath),
  localOpenDownloads: (root: 's3' | 'db', subPath?: string) => ipcRenderer.invoke('local:openDownloads', root, subPath),
  openGithub: () => ipcRenderer.invoke('app:openGithub'),
  workspaceGet: () => ipcRenderer.invoke('workspace:get'),
  workspacePick: () => ipcRenderer.invoke('workspace:pick'),
  workspaceSave: (dir: string) => ipcRenderer.invoke('workspace:save', dir),
  workspaceOpen: () => ipcRenderer.invoke('workspace:open'),
  localEraseColumn: (filePath: string, colKey: string) => ipcRenderer.invoke('local:eraseColumn', filePath, colKey),
  localListDownloads: (root: 's3' | 'db', subPath?: string) => ipcRenderer.invoke('local:listDownloads', root, subPath),
  localDeleteDownload: (absolutePath: string) => ipcRenderer.invoke('local:deleteDownload', absolutePath),
  localClearTmp: () => ipcRenderer.invoke('local:clearTmp'),
  csvStats: (filePath: string) => ipcRenderer.invoke('csv:stats', filePath),
  cacheLoad: (filePath: string) => ipcRenderer.invoke('cache:load', filePath),
  cacheSave: (filePath: string, data: unknown) => ipcRenderer.invoke('cache:save', filePath, data),
  sheetSaveSettings: (data: unknown) => ipcRenderer.invoke('sheet:saveSettings', data),
  sheetLoadSettings: () => ipcRenderer.invoke('sheet:loadSettings'),
  lorebookList: () => ipcRenderer.invoke('lorebook:list'),
  lorebookRead: (absPath: string) => ipcRenderer.invoke('lorebook:read', absPath),
  lorebookWrite: (absPath: string, content: string) => ipcRenderer.invoke('lorebook:write', absPath, content),
  lorebookDelete: (absPath: string) => ipcRenderer.invoke('lorebook:delete', absPath),
  lorebookNewPath: (product: string, csvName: string, colLabel: string) => ipcRenderer.invoke('lorebook:newPath', product, csvName, colLabel),
  lorebookGetColumnComments: (csvName: string) => ipcRenderer.invoke('lorebook:getColumnComments', csvName),
  lorebookGetCategories: () => ipcRenderer.invoke('lorebook:getCategories'),
  lorebookSetCategories: (cats: string[]) => ipcRenderer.invoke('lorebook:setCategories', cats),
  productLoadConfig: () => ipcRenderer.invoke('product:loadConfig'),
  productSaveConfig: (data: unknown) => ipcRenderer.invoke('product:saveConfig', data),
  dbCloseTunnel: (slot: string) => ipcRenderer.invoke('db:closeTunnel', slot),
  dbAbortExport: () => ipcRenderer.invoke('db:abortExport'),
  onExportProgress: (cb: (data: unknown) => void) => ipcRenderer.on('db:exportProgress', (_e, data) => cb(data)),
  offExportProgress: () => ipcRenderer.removeAllListeners('db:exportProgress'),
  dbTestConnection: (slot: string) => ipcRenderer.invoke('db:testConnection', slot),
  dbListSchemas: (slot: string, search: string, offset?: number) => ipcRenderer.invoke('db:listSchemas', slot, search, offset),
  dbListTables: (slot: string, schema: string) => ipcRenderer.invoke('db:listTables', slot, schema),
  dbExportTables: (slot: string, schema: string, tables: string[]) => ipcRenderer.invoke('db:exportTables', slot, schema, tables),
  dbExportSchemas: (slot: string, schemas: string[]) => ipcRenderer.invoke('db:exportSchemas', slot, schemas),
  dbListSlots: () => ipcRenderer.invoke('db:listSlots'),
  dbLoadSlot: (slot: string) => ipcRenderer.invoke('db:loadSlot', slot),
  dbSaveSlot: (slot: string, config: unknown) => ipcRenderer.invoke('db:saveSlot', slot, config),
  sshPickPemFile: () => ipcRenderer.invoke('ssh:pickPemFile'),
  hermesLoadConfig: () => ipcRenderer.invoke('hermes:loadConfig'),
  hermesSaveConfig: (cfg: unknown) => ipcRenderer.invoke('hermes:saveConfig', cfg),
  hermesTestConnection: () => ipcRenderer.invoke('hermes:testConnection'),
  hermesGetSessions: () => ipcRenderer.invoke('hermes:getSessions'),
  hermesGetMessages: (sessionId: string) => ipcRenderer.invoke('hermes:getMessages', sessionId),
  keyinfoReindex: (product: string | null, fileSources: unknown) => ipcRenderer.invoke('keyinfo:reindex', product, fileSources),
  keyinfoLoad: (product: string | null) => ipcRenderer.invoke('keyinfo:load', product),
  keyinfoSavePins: (product: string | null, pins: unknown[]) => ipcRenderer.invoke('keyinfo:savePins', product, pins),
  keyinfoSaveLayout: (product: string | null, pins: unknown[], folders: unknown[]) => ipcRenderer.invoke('keyinfo:saveLayout', product, pins, folders),
  keyinfoIndex: (product: string | null, fileSources: unknown) => ipcRenderer.invoke('keyinfo:index', product, fileSources),
  onKeyinfoProgress: (cb: (data: { done: number; total: number }) => void) => ipcRenderer.on('keyinfo:progress', (_e, d) => cb(d)),
  offKeyinfoProgress: () => ipcRenderer.removeAllListeners('keyinfo:progress'),
  keynoteList: (product: string | null) => ipcRenderer.invoke('keynote:list', product),
  keynoteSave: (product: string | null, notes: unknown[]) => ipcRenderer.invoke('keynote:save', product, notes),
  keynoteCandidates: (product: string | null) => ipcRenderer.invoke('keynote:candidates', product),
  keynoteAcceptCandidate: (product: string | null, signature: string) => ipcRenderer.invoke('keynote:acceptCandidate', product, signature),
  keynoteRejectCandidate: (product: string | null, signature: string) => ipcRenderer.invoke('keynote:rejectCandidate', product, signature),
  keyinfoListRelations: () => ipcRenderer.invoke('keyinfo:listRelations'),
  keyinfoSaveRelations: (groups: unknown[]) => ipcRenderer.invoke('keyinfo:saveRelations', groups),
  backupList: () => ipcRenderer.invoke('backup:list'),
  backupSave: (title: string, comment: string) => ipcRenderer.invoke('backup:save', title, comment),
  backupRestore: (id: string) => ipcRenderer.invoke('backup:restore', id),
  backupDelete: (id: string) => ipcRenderer.invoke('backup:delete', id),
})
